/* SECAM sets the colour from the luminance bits alone. */
static const uint32_t secam_colors[8] = {
    0x000000, 0x2121ff, 0xf03c79, 0xff50ff, 0x7fff00, 0x7fffff, 0xffff3f, 0xffffff,
};

typedef enum { PAL_AUTO, PAL_NTSC, PAL_PAL, PAL_SECAM } PaletteMode;

/* Atari2600State comes first, so the API's pointer is also an A26Wii *. */
typedef struct {
    Atari2600State s;
    MosConfig      cfg;          /* our copy; s.cfg points here (jacks can change) */
    PaletteMode    palette;
    bool           phosphor;
    int            shown_palette;   /* palette loaded into the video layer, -1 = none */
    bool           paused_view;
    uint32_t       emu_us;          /* time the last emulated frame took (autotest) */
    uint32_t       draw_us;         /* ...and drawing it into the canvas */
    uint32_t       emu_sum, emu_max, emu_n, avg_us, max_us;   /* 60-frame stats */
    u64            fps_t0;
    uint32_t       fps_frames, fps;                           /* frames per Wii second */
    uint32_t       loop_us, present_us, poll_us, n_run;       /* last loop iteration */
    uint32_t       shown_loop, shown_present, shown_run, shown_queue;   /* ...last one that ran */
    uint32_t       iters, ips;                                /* loop iterations per Wii second */
    uint32_t       underruns0, shown_underruns;               /* audio refills that ran dry */
} A26Wii;

static PaletteMode effective_palette(const A26Wii *w)
{
    if (w->palette != PAL_AUTO) return w->palette;
    if (w->cfg.is_secam) return PAL_SECAM;
    return w->s.pal ? PAL_PAL : PAL_NTSC;      /* s.pal: machine, or detected */
}

static void load_palette(A26Wii *w)
{
    PaletteMode p = effective_palette(w);
    if ((int)p == w->shown_palette) return;
    for (int i = 0; i < 128; i++) {
        uint32_t rgb = p == PAL_SECAM ? secam_colors[i & 7u]
                     : (p == PAL_PAL ? pal_palette : ntsc_palette)[i];
        wii_video_set_color(WII_COL_MACHINE + i, rgb);
    }
    w->shown_palette = (int)p;
}

/* ── Controller ports (as upstream) ──────────────────────────────────────── */

static bool is_joystick(A2600Controller c)
{
    return c == A2600_CTRL_CX40 || c == A2600_CTRL_CX10;
}

/* Which paddle (0-3) player p (0/1) turns, or -1. */
static int player_paddle(const Atari2600State *s, int p)
{
    if (s->cfg->a2600_ports[0] == A2600_CTRL_CX30) return p;
    if (s->cfg->a2600_ports[1] == A2600_CTRL_CX30) return 2 + p;
    return -1;
}

static uint8_t a26_read_pa(void *ud)
{
    const Atari2600State *s = ud;
    uint32_t h = s->held;
    uint8_t v = 0xFF;
    for (int port = 0; port < 2; port++) {
        A2600Controller c = s->cfg->a2600_ports[port];
        int shift = port ? 0 : 4;
        if (is_joystick(c)) {
            int base = port ? A26_ACT_P2_UP : A26_ACT_P1_UP;
            if (h & GEMU_ACTION(base + 0)) v &= (uint8_t)~(0x1u << shift);   /* up */
            if (h & GEMU_ACTION(base + 1)) v &= (uint8_t)~(0x2u << shift);   /* down */
            if (h & GEMU_ACTION(base + 2)) v &= (uint8_t)~(0x4u << shift);   /* left */
            if (h & GEMU_ACTION(base + 3)) v &= (uint8_t)~(0x8u << shift);   /* right */
        } else if (c == A2600_CTRL_CX30) {   /* paddle buttons on the right/left lines */
            for (int p = 0; p < 2; p++)
                if (player_paddle(s, p) == port * 2 + p &&
                    (h & GEMU_ACTION(p ? A26_ACT_P2_FIRE : A26_ACT_P1_FIRE)))
                    v &= (uint8_t)~((p ? 0x4u : 0x8u) << shift);
        }
    }
    return v;
}

static uint8_t a26_read_pb(void *ud)
{
    const Atari2600State *s = ud;
    uint8_t v = 0x3F;   /* Color; buttons released; bits 2, 4, 5 float high */
    if (s->held & GEMU_ACTION(A26_ACT_RESET))  v &= (uint8_t)~0x01u;
    if (s->held & GEMU_ACTION(A26_ACT_SELECT)) v &= (uint8_t)~0x02u;
    if (!s->color)    v &= (uint8_t)~0x08u;
    if (s->diff_a[0]) v |= 0x40u;
    if (s->diff_a[1]) v |= 0x80u;
    return v;
}

/* Joystick fire buttons go to INPT4/5; paddles to the pot inputs. */
static void update_tia_inputs(Atari2600State *s)
{
    for (int port = 0; port < 2; port++) {
        bool fire = is_joystick(s->cfg->a2600_ports[port]) &&
                    (s->held & GEMU_ACTION(port ? A26_ACT_P2_FIRE : A26_ACT_P1_FIRE));
        s->tia.fire[port] = fire;
    }
    for (int i = 0; i < 4; i++) {
        bool connected = s->cfg->a2600_ports[i / 2] == A2600_CTRL_CX30;
        s->tia.pot_charge[i] = connected
            ? (uint32_t)(TIA_LINE_CLOCKS * (4.0 + s->paddle[i] * 230.0)) : UINT32_MAX;
    }
}

/* The 240 lines to show, centred on what the program un-blanks (as upstream). */
static void update_window(Atari2600State *s)
{
    const Tia *t = &s->tia;
    int start;
    if (t->done_first_lit >= 0 && t->done_last_lit - t->done_first_lit >= 100)
        start = (t->done_first_lit + t->done_last_lit + 1) / 2 - A2600_FB_H / 2;
    else
        start = (t->frame_lines - A2600_FB_H) / 2;
    if (start < 0) start = 0;
    if (start > TIA_MAX_LINES - A2600_FB_H) start = TIA_MAX_LINES - A2600_FB_H;
    if (abs(start - s->window_start) > 4) s->window_start = start;
    if (!s->cfg->is_pal && !s->cfg->is_secam) s->pal = t->frame_lines >= 290;
}

/* ── Cartridge ───────────────────────────────────────────────────────────── */

/* The built-in test cart (4K, no bank switching), loaded from memory. */
static bool load_builtin(A2600Cart *c)
{
    uint8_t *rom = malloc(testcart_a26_size);
    if (!rom) return false;
    memcpy(rom, testcart_a26, testcart_a26_size);
    double hz = c->cpu_hz;
    a26_cart_free(c);
    memset(c, 0, sizeof(*c));
    c->cpu_hz = hz;
    c->rom = rom;
    c->rom_size = (uint32_t)testcart_a26_size;
    c->type = A26_CART_4K;
    c->banks = 1;
    a26_cart_reset(c);
    return true;
}

Atari2600State *atari2600_create(const MosConfig *cfg)
{
    A26Wii *w = calloc(1, sizeof(*w));
    if (!w) { wii_set_error("Out of memory"); return NULL; }
    Atari2600State *s = &w->s;
    w->cfg = *cfg;
    w->shown_palette = -1;
    s->cfg = &w->cfg;
    s->color = true;
    for (int i = 0; i < 4; i++) s->paddle[i] = 0.5;
    s->color_hz = cfg->is_pal || cfg->is_secam ? A2600_COLOR_HZ_PAL : A2600_COLOR_HZ_NTSC;
    s->pal = cfg->is_pal;
    s->window_start = 20;

    s->cart.cpu_hz = s->color_hz / 3.0;
    bool ok = cfg->cart_path ? a26_cart_load(&s->cart, cfg->cart_path) : load_builtin(&s->cart);
    if (!ok) {
        wii_set_error("Not a 2600 cartridge");
        free(w);
        return NULL;
    }
    if (cfg->cart_path) snprintf(s->cart_path, sizeof(s->cart_path), "%s", cfg->cart_path);

    tia_init(&s->tia);
    if (cfg->sound != MOS_SOUND_NONE)
        tia_sound_init(&s->tia.sound, s->color_hz / 114.0, true);
    if (!s->tia.sound.tia_rate) s->tia.sound.tia_rate = s->color_hz / 114.0;

    m6532_init(&s->riot);
    s->riot.read_pa = a26_read_pa;
    s->riot.read_pb = a26_read_pb;
    s->riot.ud = s;

    mos6502_init(&s->cpu);
    a26_bus_attach(s);
    mos_cpu_apply(&s->cpu, cfg->cpu);
    s->cpu.dummy_cycles = true;   /* hotspots see every bus cycle */

    a26_bus_power_on(s);
    return s;
}

void atari2600_destroy(Atari2600State *s)
{
    if (!s) return;
    wii_video_set_phosphor(false);
    tia_sound_destroy(&s->tia.sound);
    a26_cart_free(&s->cart);
    free((A26Wii *)s);
}

/* ── Input: Wii controllers -> 2600 actions ──────────────────────────────── */
/*
 * Controller 1 is the left joystick, controller 2 the right: D-pad (stick)
 * moves, 2 or 1 (GC A or B) fires.  + (GC X) is Game Reset, - (GC Y) Game
 * Select, on any controller.  Paddles turn with left/right.
 */
static uint32_t actions_from(const WiiInput *in)
{
    uint32_t a = 0;
    for (int p = 0; p < 2; p++) {
        uint32_t b = in->port[p];
        int base = p ? A26_ACT_P2_UP : A26_ACT_P1_UP;
        if (b & WII_BTN_UP)    a |= GEMU_ACTION(base + 0);
        if (b & WII_BTN_DOWN)  a |= GEMU_ACTION(base + 1);
        if (b & WII_BTN_LEFT)  a |= GEMU_ACTION(base + 2);
        if (b & WII_BTN_RIGHT) a |= GEMU_ACTION(base + 3);
        if (b & (WII_BTN_ACCEPT | WII_BTN_BACK)) a |= GEMU_ACTION(base + 4);
    }
    if (in->held & WII_BTN_PLUS)  a |= GEMU_ACTION(A26_ACT_RESET);
    if (in->held & WII_BTN_MINUS) a |= GEMU_ACTION(A26_ACT_SELECT);
    return a;
}

/* As upstream handle_input (switch toggles, paddles), without the mouse. */
static void handle_input(Atari2600State *s)
{
    uint32_t h = s->held;
    if (s->inject_frames > 0) { h |= s->inject_mask; s->inject_frames--; }
    s->held = h;
    uint32_t pressed = h & ~s->prev_held;
    s->prev_held = h;
    if (pressed & GEMU_ACTION(A26_ACT_COLOR))      s->color = !s->color;
    if (pressed & GEMU_ACTION(A26_ACT_LEFT_DIFF))  s->diff_a[0] = !s->diff_a[0];
    if (pressed & GEMU_ACTION(A26_ACT_RIGHT_DIFF)) s->diff_a[1] = !s->diff_a[1];
    for (int p = 0; p < 2; p++) {
        int i = player_paddle(s, p);
        if (i < 0) continue;
        int left = p ? A26_ACT_P2_LEFT : A26_ACT_P1_LEFT, right = left + 1;
        if (h & GEMU_ACTION(left))  s->paddle[i] += 0.02;
        if (h & GEMU_ACTION(right)) s->paddle[i] -= 0.02;
        if (s->paddle[i] < 0) s->paddle[i] = 0;
        if (s->paddle[i] > 1) s->paddle[i] = 1;
    }
    update_tia_inputs(s);
}

/* ── Drawing ─────────────────────────────────────────────────────────────── */

/* 240 lines x 160 pixels -> 4x horizontally, 2x vertically (640 x 480). */
static void draw_game(void *ud)
{
    A26Wii *w = ud;
    Atari2600State *s = &w->s;
    load_palette(w);
    const int W = wii_video_width(), H = wii_video_height();
    uint8_t *canvas = wii_video_canvas();
    const int sx = W / TIA_WIDTH, sy = H >= 2 * A2600_FB_H ? 2 : 1;
    const int x0 = (W - TIA_WIDTH * sx) / 2, y0 = (H - A2600_FB_H * sy) / 2;

    /* Clear only what the picture doesn't cover (PAL's extra lines). */
    if (y0 > 0) {
        wii_video_fill(0, 0, W, y0, WII_COL_BLACK);
        wii_video_fill(0, y0 + A2600_FB_H * sy, W, H - y0 - A2600_FB_H * sy, WII_COL_BLACK);
    }
    if (x0 > 0) wii_video_clear(WII_COL_BLACK);
    const uint8_t (*frame)[TIA_WIDTH] = tia_frame(&s->tia);
    for (int y = 0; y < A2600_FB_H; y++) {
        const uint8_t *src = frame[s->window_start + y];
        uint8_t *dst = canvas + (size_t)(y0 + y * sy) * W + x0;
        if (sx == 4 && ((uintptr_t)dst & 3u) == 0) {      /* one word per TIA pixel */
            uint32_t *d4 = (uint32_t *)dst;
            for (int x = 0; x < TIA_WIDTH; x++)
                d4[x] = (uint32_t)(WII_COL_MACHINE + (src[x] >> 1)) * 0x01010101u;
        } else {
            for (int x = 0; x < TIA_WIDTH; x++)
                memset(dst + x * sx, WII_COL_MACHINE + (src[x] >> 1), (size_t)sx);
        }
        for (int r = 1; r < sy; r++) memcpy(dst + (size_t)r * W, dst, (size_t)(TIA_WIDTH * sx));
    }
    if (w->paused_view)
        wii_video_text(16, 16, 2, WII_COL_ACCENT, "PAUSED");
#ifdef GEMU_WII_AUTOTEST
    wii_video_textf(16, H - 58, 1, WII_COL_WHITE,
                    "frame %llu  pc=%04X  emu %u + draw %u + convert %u us  %s",
                    (unsigned long long)s->tia.frame_count, s->cpu.PC, w->emu_us,
                    w->draw_us, wii_video_convert_us, a26_cart_type_name(s->cart.type));
    wii_video_textf(16, H - 46, 1, WII_COL_WHITE, "emu avg %u max %u us (60 frames)  %u fps",
                    w->avg_us, w->max_us, w->fps);
    wii_video_textf(16, H - 34, 1, WII_COL_WHITE,
                    "loop %u: present %u, %u frames, queue %u  %u loops/s  underruns %u since start",
                    w->shown_loop, w->shown_present, w->shown_run, w->shown_queue, w->ips,
                    w->shown_underruns);
#endif
}

/* ── Menu bar: Console, Video, Input ─────────────────────────────────────── */

static void press_switch(void *ud, int action)
{
    Atari2600State *s = ud;
    s->inject_mask = GEMU_ACTION(action);
    s->inject_frames = 10;
}
static bool is_color(void *ud, int arg)  { return ((Atari2600State *)ud)->color == (bool)arg; }
static void set_color(void *ud, int arg) { ((Atari2600State *)ud)->color = arg; }
/* arg: jack * 2 + (A ? 1 : 0) */
static bool diff_is(void *ud, int arg)   { return ((Atari2600State *)ud)->diff_a[arg / 2] == (bool)(arg & 1); }
static void diff_set(void *ud, int arg)  { ((Atari2600State *)ud)->diff_a[arg / 2] = arg & 1; }

static bool palette_is(void *ud, int arg)  { return ((A26Wii *)ud)->palette == (PaletteMode)arg; }
static void palette_set(void *ud, int arg) { ((A26Wii *)ud)->palette = (PaletteMode)arg; }
static bool phosphor_on(void *ud, int arg) { (void)arg; return ((A26Wii *)ud)->phosphor; }
static void phosphor_toggle(void *ud, int arg)
{
    (void)arg;
    A26Wii *w = ud;
    w->phosphor = !w->phosphor;
    wii_video_set_phosphor(w->phosphor);
}

/* arg: jack * 4 + A2600Controller */
static bool jack_is(void *ud, int arg)
{
    return ((A26Wii *)ud)->cfg.a2600_ports[arg / 4] == (A2600Controller)(arg % 4);
}
static void jack_set(void *ud, int arg)
{
    A26Wii *w = ud;
    w->cfg.a2600_ports[arg / 4] = (A2600Controller)(arg % 4);
    update_tia_inputs(&w->s);
}

static void radio(GemuMenu *m, const char *label, void (*set)(void *, int),
                  bool (*is)(void *, int), void *ud, int arg)
{
    GemuMenuItem *it = gemu_menu_add(m, GEMU_MENU_RADIO, label, set, ud, arg);
    it->checked = is;
}

