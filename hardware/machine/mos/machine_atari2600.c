static void menu_reset(void *ud) { a26_bus_power_on(ud); }

/* ── Run loop ────────────────────────────────────────────────────────────── */

/* Pacing: one emulated frame per vblank (the 2600's ~59.92 Hz is all but
 * the Wii's 59.94), nudged by the audio queue so sound never runs dry or
 * drifts behind: 2 frames when it is under one hardware buffer, none when it
 * is more than ~4 frames ahead (which is also how a 50 Hz PAL game skips
 * every 6th vblank).  Without audio, the frame's real duration paces it. */
#define FRAME_SAMPLES (TIA_SOUND_RATE / 60u)
#define QUEUE_LOW     SDL_AUDIO_WII_CHUNK
#define QUEUE_HIGH    (SDL_AUDIO_WII_CHUNK + 4u * FRAME_SAMPLES)
#define MAX_FRAMES_PER_VBLANK 2

static int frames_wanted(const Atari2600State *s)
{
    uint32_t q = tia_sound_queued(&s->tia.sound) / (uint32_t)sizeof(float);
    return q < QUEUE_LOW ? 2 : q > QUEUE_HIGH ? 0 : 1;
}

static void run_frame(A26Wii *w)
{
    Atari2600State *s = &w->s;
    u64 t0 = gettime();
    while (!s->tia.frame_ready) a26_bus_step(s);
    s->tia.frame_ready = false;
    s->frame_start_cycle = s->cpu.cycle_count;
    tia_sound_flush(&s->tia.sound);
    update_window(s);
    w->emu_us = (uint32_t)ticks_to_microsecs(diff_ticks(t0, gettime()));
    w->emu_sum += w->emu_us;
    if (w->emu_us > w->emu_max) w->emu_max = w->emu_us;
    if (++w->emu_n == 60) {
        w->avg_us = w->emu_sum / 60; w->max_us = w->emu_max;
        w->emu_sum = w->emu_max = w->emu_n = 0;
    }
    w->fps_frames++;
    if (!w->fps_t0) w->fps_t0 = gettime();
    if (ticks_to_millisecs(diff_ticks(w->fps_t0, gettime())) >= 1000) {
        w->fps = w->fps_frames; w->fps_frames = 0; w->fps_t0 = gettime();
        w->ips = w->iters; w->iters = 0;
    }
}

void atari2600_run(Atari2600State *s, const MosConfig *cfg)
{
    (void)cfg;
    A26Wii *w = (A26Wii *)s;
    WiiMenubar *menubar = wii_menubar_new(&(WiiMenubarHooks){
        .reset = menu_reset, .input_items = a26_input_items, .menus = a26_menus,
        .draw_frame = draw_game, .ud = w,
    });

    u64 t0 = gettime();
    uint64_t emu_cycles = 0;          /* emulated since t0, when there is no audio */

    for (;;) {
        u64 l0 = gettime();
        WiiInput in = wii_input_poll(true);
        w->poll_us = (uint32_t)ticks_to_microsecs(diff_ticks(l0, gettime()));
        WiiExit sys = wii_system_exit_requested();
        if (sys != WII_EXIT_NONE) { wii_request_exit(sys); break; }

        if (in.pressed & WII_BTN_PAUSE) {            /* HOME: menu bar */
            s->held = 0;
            WiiExit leave = wii_menubar_open(menubar);
            if (leave != WII_EXIT_NONE) { wii_request_exit(leave); break; }
            t0 = gettime(); emu_cycles = 0;
            continue;
        }

        s->held = actions_from(&in);
        bool paused = wii_menubar_paused(menubar);
#ifdef GEMU_WII_AUTOTEST
        paused |= wii_autotest_frozen();
#endif
        if (!paused) {
            handle_input(s);
            w->n_run = 0;
            int want = s->tia.sound.dev ? frames_wanted(s) : MAX_FRAMES_PER_VBLANK;
            for (int n = 0; n < want; n++) {
                if (!s->tia.sound.dev) {
                    uint64_t real_us = ticks_to_microsecs(diff_ticks(t0, gettime()));
                    if (emu_cycles * 3000000.0 / s->color_hz >= (double)real_us) break;
                }
                uint64_t c0 = s->cpu.cycle_count;
                run_frame(w);
                w->n_run++;
                emu_cycles += s->cpu.cycle_count - c0;
            }
        }

        w->paused_view = wii_menubar_paused(menubar);
        u64 d0 = gettime();
        draw_game(w);
        w->draw_us = (uint32_t)ticks_to_microsecs(diff_ticks(d0, gettime()));
        u64 p0 = gettime();
        wii_video_present();
        w->present_us = (uint32_t)ticks_to_microsecs(diff_ticks(p0, gettime()));
        w->loop_us = (uint32_t)ticks_to_microsecs(diff_ticks(l0, gettime()));
        if (!paused) {
            w->shown_loop = w->loop_us; w->shown_present = w->present_us;
            w->shown_run = w->n_run;
            if (!w->underruns0) w->underruns0 = sdl_audio_wii_underruns + 1;
            w->shown_underruns = sdl_audio_wii_underruns + 1 - w->underruns0;
            w->shown_queue = (uint32_t)(tia_sound_queued(&s->tia.sound) / sizeof(float));
            w->iters++;
        }
    }
    wii_menubar_free(menubar);
}
